#!/usr/bin/env python3
"""Generate executable thermal test artifacts (P10) from the handoff plans.

Reads the pinned plan CSVs in Cutting_Agent_Handoff_2026-10-29/data/ (18
steady-state TS tests, 17 thermal-fault TF tests) and emits:
  tests/P10-thermal/procedures.md        - executable procedure per test
  tests/P10-thermal/records/<id>.json    - evidence-record template per test
  tests/P10-thermal/manifest.json        - input hashes and test inventory

Physical execution is a hardware gate (D8): the records ship with
"executed": false and must not be relabelled without real measurements.
"""
from __future__ import annotations

import csv
import hashlib
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "Cutting_Agent_Handoff_2026-10-29" / "data"
OUT = ROOT / "tests" / "P10-thermal"


def sha256(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def load(name: str):
    with (DATA / name).open(newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


INSTRUMENTS = """**Instrumentation (all tests):** calibrated thermocouples/PT100 on every guarded
temperature location (driver cases, motor bodies, PSU, choke/bleed, wiring
terminations), inlet-air sensors at both filter paths and at the driver inlet,
ambient sensor at the room reference point, hot-wire/pressure instruments for
installed flow, power analyser on the cabinet input, door/filter differential
sensor. Calibration certificates recorded in the test record; instrument
uncertainty included in every stated margin (handoff 11.1/11.2).
"""

METHOD = """**Method:** assemble the real cabinet with the final filters, doors, wiring and
layout; run the declared duty until thermal steady state (guarded-temperature
drift < 0.5 K over 30 min); record the complete temperature/flow/power grid and
the raw sensor logs; compute energy and mass imbalance of the measured air
(imbalance is computed from measurements, never input as a target); state every
margin as (limit - measured worst) with its uncertainty. Raw data paths and
input hashes go into the record template. No simulated temperature is recorded
as measured.
"""


def main() -> None:
    steady = load("thermal-steady-plan.csv")
    fault = load("thermal-fault-plan.csv")
    (OUT / "records").mkdir(parents=True, exist_ok=True)

    manifest = {
        "model": "P10 thermal qualification artifacts",
        "inputs": {
            "thermal-steady-plan.csv": sha256(DATA / "thermal-steady-plan.csv"),
            "thermal-fault-plan.csv": sha256(DATA / "thermal-fault-plan.csv"),
        },
        "tests": [r["test_id"] for r in steady] + [r["test_id"] for r in fault],
        "executed": False,
        "note": "records ship executed=false; physical execution is the D8 hardware gate",
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    md = ["# P10 cabinet thermal qualification procedures (18 TS + 17 TF)", "",
          "Generated by `tools/generate_thermal_tests.py` from the pinned handoff",
          "plans. These procedures are executable as written on the physical cabinet;",
          "the shipped record templates carry `executed: false` until real data exists.", "",
          INSTRUMENTS, METHOD]

    for r in steady:
        tid = r["test_id"]
        md += [f"## {tid} — steady state ({r['duty']})", "",
               f"- Ambient: {r['ambient_C']} C (room reference).",
               f"- Mains case: {r['mains_voltage_case']}.",
               f"- Duty: {r['duty']}.",
               f"- Filter case: {r['filter_case']}.",
               f"- Airflow/frequency: {r['frequency_Hz']}.",
               f"- Acceptance: {r['acceptance']}.",
               "- Steps: 1) configure case; 2) instrument; 3) run to steady state;",
               "  4) record full grid + raw logs; 5) compute imbalances and margins;",
               "  6) complete `records/%s.json`; 7) sign off only if every individual limit holds." % tid,
               ""]
        record = {
            "template_only": True,
            "executed": False,
            "test_id": tid,
            "kind": "steady_state",
            "case": {"ambient_C": r["ambient_C"], "mains": r["mains_voltage_case"],
                     "duty": r["duty"], "filter": r["filter_case"], "airflow": r["frequency_Hz"]},
            "acceptance": r["acceptance"],
            "measurements": {
                "ambient_C": None, "inlet_driver_C": None, "normal_inlet_limit_C": 45.0,
                "guarded_temperatures_C": {}, "installed_flow_m3_h": None,
                "energy_imbalance_pct": None, "mass_imbalance_pct": None,
                "input_power_W": None, "raw_data_path": None,
            },
            "margins": {},
            "operator": None,
            "instruments": [],
            "result": None,
        }
        (OUT / "records" / f"{tid}.json").write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    for r in fault:
        tid = r["test_id"]
        md += [f"## {tid} — thermal fault: {r['scenario']}", "",
               f"- Required observation: {r['required_observation']}.",
               "- Steps: 1) reach steady state at the declared worst normal case;",
               "  2) induce the fault exactly as described (real failure, not a simulated",
               "     temperature); 3) record guarded temperatures, trip/detection latency,",
               "     post-trip soak and the restart behaviour; 4) verify no unsafe",
               "     auto-restart occurs; 5) complete `records/%s.json`." % tid,
               ""]
        record = {
            "template_only": True,
            "executed": False,
            "test_id": tid,
            "kind": "fault",
            "scenario": r["scenario"],
            "acceptance": r["required_observation"],
            "measurements": {
                "worst_guarded_temperature_C": None,
                "guarded_limit_C": None,
                "shutdown_latency_s": None,
                "post_trip_soak_C": None,
                "raw_data_path": None,
            },
            "restart_result": None,
            "operator": None,
            "instruments": [],
            "result": None,
        }
        (OUT / "records" / f"{tid}.json").write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    (OUT / "procedures.md").write_text("\n".join(md), encoding="utf-8")
    print(f"generated {len(steady)} TS + {len(fault)} TF procedures and records under {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
